import { z } from "zod";
import { llmConfigured, llmJson } from "@/lib/ai/llm";
import { GenreTemplate, beats, genreOf } from "./genres";

/**
 * Topic -> production script for the Flow Agent: one entry per ~10 s clip, with the visual, the camera and the exact
 * words spoken (in the channel's language), plus fixed character/look descriptions repeated so every clip matches,
 * and the publishing metadata (title, caption, hashtags). Falls back to the genre's beat structure without an LLM.
 */

export const LANGUAGE_NAMES: Record<string, string> = {
  vi: "Vietnamese",
  en: "English",
  ja: "Japanese",
  ko: "Korean",
  zh: "Chinese",
  th: "Thai",
  id: "Indonesian",
  es: "Spanish",
  fr: "French",
};
export const languageName = (code: string) => LANGUAGE_NAMES[code] || code;

export interface ScriptInput {
  topic: string;
  angle?: string | null;
  genre: string;
  durationSec: number;
  clipSeconds: number;
  language: string;
  channelName?: string;
  niche?: string;
  styleBible?: string;
  hashtags?: string[];
}

export interface ScriptScene {
  beat: string;
  visual: string;
  camera: string;
  speech: string; // "" when nobody speaks
}

export interface ProductionScript {
  /** "agent" = no written scenes: the Flow Agent plans the clips itself from the topic + genre structure (LLM unavailable) */
  mode?: "script" | "agent";
  /** why the fallback was used */
  warning?: string;
  title: string;
  logline: string;
  characters: string;
  look: string;
  scenes: ScriptScene[];
  caption: string;
  hashtags: string[];
  usedAI: boolean;
}

const scriptSchema = z.object({
  title: z.string().min(3).max(120),
  logline: z.string().min(5).max(400),
  characters: z.string().max(1200),
  look: z.string().max(800),
  scenes: z
    .array(
      z.object({
        beat: z.string().max(120),
        visual: z.string().min(10).max(700),
        camera: z.string().max(200),
        speech: z.string().max(300),
      })
    )
    .min(1)
    .max(12),
  caption: z.string().min(5).max(600),
  hashtags: z.array(z.string().max(40)).max(10),
});

export function clipCount(durationSec: number, clipSeconds: number): number {
  return Math.max(1, Math.round(durationSec / Math.max(1, clipSeconds)));
}

function systemPrompt(g: GenreTemplate, lang: string): string {
  const voice =
    g.voice === "dialogue"
      ? `Characters speak short natural lines in ${lang}. Put the exact words in "speech" (prefix with the speaker's name, e.g. "Minh: …").`
      : g.voice === "voiceover"
        ? `A narrator speaks in ${lang}. Put the exact narration in "speech" (no speaker prefix).`
        : `Nobody speaks: "speech" must be an empty string; describe the ambient sound inside "visual".`;
  return `You are a showrunner writing scripts for short vertical videos generated by Google Veo 3.1 in Google Flow.
Genre: ${g.label} — ${g.description}
Genre guidance: ${g.guidance}

Hard constraints:
- Each scene is ONE continuous ~10 second clip generated on its own, so it must be self-explanatory: describe who/what is in frame, where, the action and the lighting concretely.
- "characters": fixed, reusable description of every recurring character/product (name, age, face, hair, clothing, colors) — it is repeated in every clip so they look identical. Empty string if there are none.
- "look": the visual style for the whole video (lens, light, color grade), consistent across clips.
- "visual" and "camera" are in English (Veo works best in English). "speech" is in ${lang} and must fit in 10 seconds (max ~20 words; dialogue max ~12 words).
- ${voice}
- No on-screen text, no subtitles, no logos, no watermarks. No real celebrities or politicians, no brands unless given, nothing sexual, violent-graphic, hateful or dangerous; no medical/financial claims.
- "title" (${lang}, max ~70 characters, catchy but not clickbait-false), "caption" in ${lang} (${g.captionStyle}), "hashtags": 5-8 relevant hashtags with "#", no spaces.
Return ONLY JSON: {"title","logline","characters","look","scenes":[{"beat","visual","camera","speech"}],"caption","hashtags"}.`;
}

/**
 * Without an LLM we do NOT invent placeholder scenes ("Scene 1: <topic>: hook…" makes poor videos). Instead the Flow
 * Agent gets the topic, the angle, the genre's guidance and beat structure and the language, and writes the scenes
 * itself (that is how Flow Agent videos were made before scripts existed, with good results).
 */
function fallbackScript(i: ScriptInput, g: GenreTemplate, n: number, warning?: string): ProductionScript {
  const plan = beats(g, n);
  return {
    mode: "agent",
    warning,
    title: i.topic.slice(0, 100),
    logline: i.angle || i.topic,
    characters: "",
    look: i.styleBible || g.look,
    scenes: plan.map((b) => ({ beat: b, visual: "", camera: "", speech: "" })),
    caption: i.angle ? `${i.topic} — ${i.angle}` : i.topic,
    hashtags: i.hashtags ?? [],
    usedAI: false,
  };
}

/** Pads/trims to exactly n scenes (the Flow Agent is asked for exactly n clips). */
function fitScenes(scenes: ScriptScene[], n: number): ScriptScene[] {
  if (scenes.length === n) return scenes;
  if (scenes.length > n) return [...scenes.slice(0, n - 1), scenes[scenes.length - 1]];
  const out = [...scenes];
  while (out.length < n) out.splice(out.length - 1, 0, { ...out[out.length - 2 >= 0 ? out.length - 2 : 0], beat: "continuation" });
  return out;
}

export async function writeScript(i: ScriptInput): Promise<ProductionScript> {
  const g = genreOf(i.genre);
  const n = clipCount(i.durationSec, i.clipSeconds);
  if (!llmConfigured()) return fallbackScript(i, g, n, "Chưa cấu hình LLM");

  const lang = languageName(i.language);
  const plan = beats(g, n);
  const user = [
    `Topic: ${i.topic}`,
    i.angle ? `Angle / hook: ${i.angle}` : "",
    i.channelName ? `Channel: ${i.channelName}${i.niche ? ` — ${i.niche}` : ""}` : "",
    i.styleBible ? `Channel visual identity (must be respected): ${i.styleBible}` : `Default look for this genre: ${g.look}`,
    `Length: ${i.durationSec} seconds = EXACTLY ${n} scenes of ~${i.clipSeconds}s.`,
    `Scene structure to follow, one beat per scene:\n${plan.map((b, k) => `${k + 1}. ${b}`).join("\n")}`,
    i.hashtags?.length ? `Always include these channel hashtags: ${i.hashtags.join(" ")}` : "",
  ]
    .filter(Boolean)
    .join("\n");

  let out: z.infer<typeof scriptSchema>;
  try {
    // budget the answer to the length: ~250 tokens per scene + metadata (an exhausted key can still afford short scripts)
    out = await llmJson({ system: systemPrompt(g, lang), user, schema: scriptSchema, temperature: 0.9, maxTokens: 700 + n * 260 });
  } catch (e: any) {
    // automation must not stall on an LLM outage / empty balance: let the Flow Agent write the scenes instead
    return fallbackScript(i, g, n, `Không viết được kịch bản bằng LLM (${String(e?.message || e).slice(0, 160)}): Flow Agent tự lên kịch bản.`);
  }
  const tags = [...new Set([...(out.hashtags || []), ...(i.hashtags || [])].map((t) => (t.startsWith("#") ? t : `#${t}`).replace(/\s+/g, "")))].slice(0, 10);
  return { ...out, scenes: fitScenes(out.scenes, n), hashtags: tags, usedAI: true };
}

/**
 * The brief handed to the Flow Agent. Flow labels its prompts "Scene k", and the tool maps clips back to scenes by that
 * label, so the brief uses the same numbering.
 */
export function scriptToBrief(s: ProductionScript, genre: string, language: string): string {
  const g = genreOf(genre);
  const lang = languageName(language);
  if (s.mode === "agent") {
    const voice =
      g.voice === "dialogue" ? `Characters speak short natural lines in ${lang}.` : g.voice === "voiceover" ? `A narrator speaks in ${lang}.` : "No speech at all: ambient sound only.";
    return [
      `Topic: ${s.title}`,
      s.logline !== s.title ? `Angle: ${s.logline}` : "",
      `Genre: ${g.label} — ${g.description}`,
      `How to make it: ${g.guidance}`,
      voice,
      `Look: ${s.look}`,
      `Structure (one clip per beat, in this order):`,
      ...s.scenes.map((sc, k) => `${k + 1}. ${sc.beat}`),
    ]
      .filter(Boolean)
      .join("\n");
  }
  const header = [
    `Title: ${s.title}`,
    `Genre: ${g.label} (${g.key}). Story: ${s.logline}`,
    s.characters.trim() ? `Characters (identical in every scene): ${s.characters.trim()}` : "",
    `Look (identical in every scene): ${s.look}`,
  ].filter(Boolean);
  const scenes = s.scenes.map((sc, k) => {
      const say = sc.speech.trim()
        ? `Spoken in ${lang}: "${sc.speech.trim()}"`
        : g.voice === "none"
          ? "No speech: natural ambient sound only."
          : "No dialogue in this scene.";
      const end = (t: string) => t.trim().replace(/[.\s]+$/, "") + ".";
      return `Scene ${k + 1} — ${sc.beat.split(":")[0]}: ${end(sc.visual)} Camera: ${end(sc.camera)} ${say}`;
  });
  return [...header, "", ...scenes].join("\n");
}
